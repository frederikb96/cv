#!/usr/bin/env bun
// Renders the experience list and the certification line of the CV from the website's data
// files (experience.yaml, accomplishments.yaml), so one source feeds the site and the CV.
//
// Usage: scripts/render-data.ts <data dir> <output dir>
// Writes experience.tex and certifications.tex into <output dir>.

import { join } from "node:path";

type CvBlock = {
  show: boolean;
  title?: string;
  organization?: string;
  location?: string;
  bullets?: string[];
};

type Position = {
  id: string;
  title: string;
  organization: string;
  location: string;
  start: string;
  end: string | null;
  cv: CvBlock;
};

type Certification = {
  id: string;
  cv: { show: boolean; label?: string; order?: number };
};

const HEADER =
  "% Generated by `make` from the website's data files (src/data in frederikb96/frederikberg).\n" +
  "% Edit those files, not this one.\n";

const LATEX_SPECIAL: Record<string, string> = {
  "\\": "\\textbackslash{}",
  "&": "\\&",
  "%": "\\%",
  "$": "\\$",
  "#": "\\#",
  "_": "\\_",
  "{": "\\{",
  "}": "\\}",
  "~": "\\textasciitilde{}",
  "^": "\\textasciicircum{}",
};

function escapeText(text: string): string {
  return text.replace(/[\\&%$#_{}~^]/g, (c) => LATEX_SPECIAL[c]);
}

function escapeUrl(url: string): string {
  return url.replace(/[%#]/g, (c) => `\\${c}`);
}

/** Escapes text for LaTeX and turns Markdown-style [text](url) links into \href. */
function inline(text: string): string {
  const link = /\[([^\]]+)\]\(([^)\s]+)\)/g;
  let out = "";
  let last = 0;
  for (const m of text.matchAll(link)) {
    out += escapeText(text.slice(last, m.index));
    out += `\\href{${escapeUrl(m[2])}}{${escapeText(m[1])}}`;
    last = m.index! + m[0].length;
  }
  return out + escapeText(text.slice(last));
}

/** "2024-05" -> "05/2024"; null -> "Present" */
function month(value: string | null): string {
  if (value === null) return "Present";
  const match = /^(\d{4})-(\d{2})$/.exec(value);
  if (!match) throw new Error(`expected YYYY-MM, got ${JSON.stringify(value)}`);
  return `${match[2]}/${match[1]}`;
}

function need<T>(value: T | undefined, what: string): T {
  if (value === undefined || value === null) throw new Error(`missing ${what}`);
  return value;
}

function renderPosition(p: Position): string {
  const cv = need(p.cv, `cv block in experience entry ${p.id}`);
  const bullets = need(cv.bullets, `cv.bullets in experience entry ${p.id}`);
  if (bullets.length === 0) throw new Error(`cv.bullets of experience entry ${p.id} is empty`);
  const items = bullets.map((b) => `            \\item ${inline(b)}`).join("\n");
  return [
    "    \\twentyitem",
    `        {${month(p.start)} -}`,
    `        {${month(p.end)}}`,
    `        {${inline(cv.title ?? p.title)}}`,
    `        {${inline(cv.location ?? p.location)}}`,
    `        {${inline(cv.organization ?? p.organization)}}`,
    "        {\\begin{itemize}",
    items,
    "        \\end{itemize}}",
    "        \\\\",
  ].join("\n");
}

function renderCertifications(certs: Certification[]): string {
  const shown = certs
    .filter((c) => c.cv?.show)
    .map((c) => ({
      label: need(c.cv.label, `cv.label in certification ${c.id}`),
      order: need(c.cv.order, `cv.order in certification ${c.id}`),
    }))
    .sort((a, b) => a.order - b.order);
  return shown.map((c) => inline(c.label)).join(" \\hspace{1mm}|\\hspace{1mm} ");
}

async function readYaml<T>(path: string): Promise<T> {
  return Bun.YAML.parse(await Bun.file(path).text()) as T;
}

const [dataDir, outDir] = process.argv.slice(2);
if (!dataDir || !outDir) {
  console.error("usage: render-data.ts <data dir> <output dir>");
  process.exit(2);
}

const positions = await readYaml<Position[]>(join(dataDir, "experience.yaml"));
const certifications = await readYaml<Certification[]>(join(dataDir, "accomplishments.yaml"));

const experience =
  HEADER +
  "\\begin{twenty}\n" +
  positions
    .filter((p) => p.cv?.show)
    .map(renderPosition)
    .join("\n") +
  "\n\\end{twenty}\n";

await Bun.write(join(outDir, "experience.tex"), experience);
await Bun.write(join(outDir, "certifications.tex"), HEADER + renderCertifications(certifications) + "\n");
